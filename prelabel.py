def guess(title, body=""):
    t = title.lower()
    for n in NOISE: t = t.replace(n.lower(), "")
    for lab, kws in RULES:
        if any(k.lower() in t for k in kws): return lab
    return "기타"
df = pd.read_csv("data/notices_raw.csv", encoding="utf-8-sig")
df["auto_label"] = df["title"].map(guess)
df["label"] = ""   # 여기에 직접 검수한 최종 분야를 적는다
df.to_csv("data/notices_labeled.csv", index=False, encoding="utf-8-sig")
